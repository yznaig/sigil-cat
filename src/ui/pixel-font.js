const width = (ch) => (G[ch] || G['?'])[0].length;
// Width in font pixels (one pixel between letters, none after the last).
export function measure(text) { let w = 0; for (const ch of text) w += width(ch) + 1; return Math.max(0, w - 1); }
// Draw at font-pixel position (x, y) on a canvas already scaled to font pixels (or at `px` canvas pixels per font pixel).
export function drawText(c, text, x, y, color, { shadow = null, px = 1 } = {}) {
  const pass = (ox, oy, fill) => {
    c.fillStyle = fill; let cx = x;
    for (const ch of text) {
      const rows = G[ch] || G['?'];
      rows.forEach((row, r) => { for (let k = 0; k < row.length; k++) if (row[k] === '#') c.fillRect((cx + k + ox) * px, (y + r + oy) * px, px, px); });
      cx += width(ch) + 1;
    }
  };
  if (shadow) pass(1, 1, shadow);
  pass(0, 0, color);
}
